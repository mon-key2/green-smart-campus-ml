# **Decision: we do not keep the engineered features.** With the engineered features the cross-validated R2 is 0.9159, against 0.9163 without them, so there is **no improvement**. The reason is the data itself: the target depends only on solar generation, so combinations of other columns cannot add information.
# The recycling rate would also be above 1 in some rows because of the inconsistent waste values from section 2.1. Honest negative results like this are part of the analysis.

# %% [markdown]
# # Stage 3: Modeling and tuning
#
# ## 3.1 Choosing the model
# We compare four models with 5-fold cross-validation **on the training set**, all using the same preprocessing (scaling and one-hot encoding):
# a **baseline** that always predicts the mean (an R2 of 0 means "no better than the mean"), **Ridge regression** (a linear model with a penalty on large coefficients),
# **Random Forest** and **Gradient Boosting** (two tree-based models that can capture non-linear patterns).

# %%
preprocess = make_preprocess('one-hot')
candidates = {
    'Mean baseline': DummyRegressor(strategy='mean'),
    'Ridge regression': Ridge(alpha=1.0),
    'Random Forest': RandomForestRegressor(n_estimators=200, min_samples_leaf=5, random_state=RANDOM_STATE, n_jobs=-1),
    'Gradient Boosting': GradientBoostingRegressor(random_state=RANDOM_STATE),
}
cmp_rows = []
for name, model in candidates.items():
    res = cross_validate(Pipeline([('pre', preprocess), ('model', model)]), X_train, y_train, cv=cv,
                         scoring=('r2', 'neg_mean_absolute_error'))
    cmp_rows.append({'model': name, 'cv_r2': res['test_r2'].mean(), 'cv_r2_std': res['test_r2'].std(),
                     'cv_MAE': -res['test_neg_mean_absolute_error'].mean()})
model_comparison = pd.DataFrame(cmp_rows)
print(model_comparison.round(4).to_string(index=False))

# %% [markdown]
# **Choice: Ridge regression.** Cross-validated R2 is 0.9163 for Ridge, 0.9113 for Random Forest and 0.9104 for Gradient Boosting, while the mean baseline is at -0.003 (MAE 2.90, 2.96 and 2.97 kWh against 10.33 kWh for the baseline). The three real models are close (the gaps are within about one standard deviation across the folds), but Ridge is the highest and the simplest.
# We choose it because (1) it has the best cross-validated score, (2) the relationship we found in the analysis is **linear** (energy saved is a share of solar generation), so a linear model is the right shape,
# (3) the other 14 features are noise, and a penalised linear model ignores them more safely than a flexible tree model, which can fit noise, and (4) it is simple, fast and easy to explain and to deploy.

