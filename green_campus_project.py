# ## 3.2 Grid search
#
# The pipeline is `preprocess -> SelectKBest -> Ridge`. The grid search tunes two things with 5-fold cross-validation on the training set:
#
# * `select__k`: how many of the 18 preprocessed columns to keep (the feature selection of section 2.6, step 2). Because it is inside the pipeline, the selection is re-fitted on each training fold.
# * `model__alpha`: the strength of the Ridge penalty.

# %%
pipe = Pipeline([('pre', make_preprocess('one-hot')),
                 ('select', SelectKBest(score_func=f_regression)),
                 ('model', Ridge())])

param_grid = {
    'select__k': [1, 2, 3, 5, 10, 'all'],
    'model__alpha': [0.01, 0.1, 1, 10, 100],
}
print('Parameter grid:', param_grid)
print('Combinations  :', 6 * 5, '| fits (5 folds):', 6 * 5 * 5)

grid = GridSearchCV(pipe, param_grid, cv=cv, scoring='r2', n_jobs=-1, return_train_score=True)
