# %% [markdown]
# ## 2.7 Encoding categorical features and scaling numeric features
#
# * **Scaling:** numeric features use `StandardScaler` (mean 0, standard deviation 1). Ridge regression penalises large coefficients, so features on very different scales (water in hundreds, occupancy below 1) must be scaled to be treated fairly.
# * **Encoding:** `Building_ID` and `Day_Type` are text and have **no natural order**. We compare three encoders inside the cross-validation pipeline, so the encoder is fitted on the training folds only:
#   one-hot encoding, label (ordinal) encoding, and the CRC32 target encoder from the earlier assignment.

# %%
cv = KFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)


def make_preprocess(kind):
    if kind == 'one-hot':
        cat = [('cat', OneHotEncoder(handle_unknown='ignore'), cat_cols)]
    elif kind == 'label (ordinal)':
        cat = [('cat', OrdinalEncoder(handle_unknown='use_encoded_value', unknown_value=-1), cat_cols)]
    else:  # CRC32 target encoding, one encoder per column
        cat = [(f'crc_{c}', CRCTargetEncoder(cols=[c], smoothing=1, min_samples_leaf=20, noise_scale=1e-3), [c]) for c in cat_cols]
    return ColumnTransformer([('num', StandardScaler(), num_cols)] + cat)


enc_rows = []
for kind in ['one-hot', 'label (ordinal)', 'CRC32 target']:
    pipe = Pipeline([('pre', make_preprocess(kind)), ('model', Ridge(alpha=1.0))])
    scores = cross_val_score(pipe, X_train, y_train, cv=cv, scoring='r2')
    enc_rows.append({'encoding': kind, 'cv_r2_mean': scores.mean(), 'cv_r2_std': scores.std()})
print(pd.DataFrame(enc_rows).round(4).to_string(index=False))

# %% [markdown]
# **Decision: one-hot encoding.** The three encoders give practically the same cross-validated R2 (0.9163 for one-hot, 0.9162 for label encoding and 0.9163 for CRC32 target encoding), so the choice does not change the result. We choose **one-hot** because
# (1) it adds no artificial order (label encoding would say B1 < B2 < B3), (2) it does not use the target (target encoding needs extra care to avoid leakage), and (3) it only uses scikit-learn, which keeps deployment simple.
# Target encoding is most useful for columns with many categories, and here there are only 3 and 2.

# %% [markdown]
# ## 2.8 Feature engineering experiment
# We tested three domain-inspired features: the **net energy balance** (solar generation minus consumption), the **energy used per occupant**, and the **recycling rate** (recycled divided by produced waste).
# We keep them only if they improve the cross-validated score.

# %%
def add_features(d):
    d = d.copy()
    d['Net_Energy_Balance'] = d['Solar_Generation_kWh'] - d['Energy_Consumption_kWh']
    d['Energy_per_Occupant'] = d['Energy_Consumption_kWh'] / d['Occupancy_Level']
    d['Recycling_Rate'] = d['Recycled_Waste_Kg'] / d['Waste_Produced_Kg']
    return d


X_train_fe = add_features(X_train)
num_cols_fe = num_cols + ['Net_Energy_Balance', 'Energy_per_Occupant', 'Recycling_Rate']
pre_fe = ColumnTransformer([('num', StandardScaler(), num_cols_fe), ('cat', OneHotEncoder(handle_unknown='ignore'), cat_cols)])
pre_base = make_preprocess('one-hot')

fe_rows = []
for name, pre, X_ in [('original features', pre_base, X_train), ('+ engineered features', pre_fe, X_train_fe)]:
    scores = cross_val_score(Pipeline([('pre', pre), ('model', Ridge(alpha=1.0))]), X_, y_train, cv=cv, scoring='r2')
    fe_rows.append({'feature set': name, 'cv_r2_mean': scores.mean(), 'cv_r2_std': scores.std()})
print(pd.DataFrame(fe_rows).round(4).to_string(index=False))
print('Rows where Recycling_Rate is above 1 (impossible):', int((X_train_fe['Recycling_Rate'] > 1).sum()))

